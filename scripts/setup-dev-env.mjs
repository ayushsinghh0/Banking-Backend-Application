#!/usr/bin/env node
/**
 * Local development bootstrap.
 *
 *   node scripts/setup-dev-env.mjs          # creates .env (random secrets) if missing, then services/<svc>/.env
 *
 * The root .env drives docker compose; the per-service .env files let you run services natively
 * (npm start / npm run dev) against the containers started with:
 *   docker compose -f docker-compose.yml -f docker-compose.dev.yml up -d postgres redis kafka kafka-init mailpit
 * Existing files are never overwritten unless --force is passed.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const force = process.argv.includes('--force');
const secret = () => crypto.randomBytes(32).toString('hex'); // hex: safe inside connection URLs

function writeIfAbsent(file, content) {
  if (fs.existsSync(file) && !force) {
    console.log(`skip   ${path.relative(root, file)} (exists)`);
    return;
  }
  fs.writeFileSync(file, content, { mode: 0o600 });
  console.log(`write  ${path.relative(root, file)}`);
}

const rootEnvFile = path.join(root, '.env');
writeIfAbsent(
  rootEnvFile,
  `# Generated by scripts/setup-dev-env.mjs for LOCAL DEVELOPMENT. Never commit this file.
POSTGRES_USER=postgres
POSTGRES_PASSWORD=${secret()}
POSTGRES_DB=banksphere
AUTH_DB_PASSWORD=${secret()}
CUSTOMER_DB_PASSWORD=${secret()}
ACCOUNT_DB_PASSWORD=${secret()}
LEDGER_DB_PASSWORD=${secret()}
NOTIFICATION_DB_PASSWORD=${secret()}
FRAUD_DB_PASSWORD=${secret()}
REDIS_PASSWORD=${secret()}
JWT_ACCESS_SECRET=${crypto.randomBytes(48).toString('base64url')}
INTERNAL_SERVICE_TOKEN=${crypto.randomBytes(48).toString('base64url')}
JWT_ACCESS_EXPIRATION=15m
JWT_REFRESH_EXPIRATION_DAYS=7
APP_BASE_URL=http://localhost:3000
CORS_ORIGINS=http://localhost:3000
SMTP_HOST=mailpit
SMTP_PORT=1025
SMTP_SECURE=false
SMTP_REQUIRE_TLS=false
MAIL_FROM="BankSphere <no-reply@banksphere.local>"
SECURITY_ALERT_EMAIL=security-team@banksphere.local
`
);

const env = Object.fromEntries(
  fs
    .readFileSync(rootEnvFile, 'utf8')
    .split(/\r?\n/)
    .filter((l) => l && !l.startsWith('#') && l.includes('='))
    .map((l) => {
      const i = l.indexOf('=');
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^"(.*)"$/, '$1')];
    })
);

const db = (user, pw, schema) =>
  `DATABASE_URL="postgresql://${user}:${env[pw]}@localhost:5432/${env.POSTGRES_DB}?schema=${schema}"`;

const common = `NODE_ENV=development
LOG_LEVEL=info
JWT_ACCESS_SECRET="${env.JWT_ACCESS_SECRET}"
JWT_ACCESS_EXPIRATION=${env.JWT_ACCESS_EXPIRATION}
INTERNAL_SERVICE_TOKEN="${env.INTERNAL_SERVICE_TOKEN}"
REDIS_URL="redis://:${env.REDIS_PASSWORD}@localhost:6380"
KAFKA_ENABLED=true
KAFKA_BROKERS=localhost:9092
TRUST_PROXY=1
`;

const smtp = `EMAIL_TRANSPORT=smtp
SMTP_HOST=localhost
SMTP_PORT=1025
SMTP_SECURE=false
SMTP_REQUIRE_TLS=false
MAIL_FROM="${env.MAIL_FROM}"
`;

const services = {
  'auth-service': `PORT=8001\nKAFKA_CLIENT_ID=auth-service\n${db('auth_svc', 'AUTH_DB_PASSWORD', 'auth_schema')}\nAPP_BASE_URL=${env.APP_BASE_URL}\nJWT_REFRESH_EXPIRATION_DAYS=${env.JWT_REFRESH_EXPIRATION_DAYS}\n${smtp}# Relaxed per-IP limits so the local e2e suite can be re-run (production defaults: 30 / 10 per 15 min)\nAUTH_RATE_LIMIT_MAX=500\nAUTH_RECOVERY_RATE_LIMIT_MAX=500\n`,
  'customer-service': `PORT=8002\n${db('customer_svc', 'CUSTOMER_DB_PASSWORD', 'customer_schema')}\n`,
  'account-service': `PORT=8003\nKAFKA_CLIENT_ID=account-service\nLEDGER_SERVICE_URL=http://localhost:8004\nCUSTOMER_SERVICE_URL=http://localhost:8002\n${db('account_svc', 'ACCOUNT_DB_PASSWORD', 'account_schema')}\n`,
  'transaction-service': `PORT=8004\nKAFKA_CLIENT_ID=transaction-service\n${db('ledger_svc', 'LEDGER_DB_PASSWORD', 'ledger_schema')}\n`,
  'notification-service': `PORT=8005\nKAFKA_CLIENT_ID=notification-service\nSECURITY_ALERT_EMAIL=${env.SECURITY_ALERT_EMAIL}\n${db('notification_svc', 'NOTIFICATION_DB_PASSWORD', 'notification_schema')}\n${smtp}`,
  'fraud-service': `PORT=8006\nKAFKA_CLIENT_ID=fraud-service\n${db('fraud_svc', 'FRAUD_DB_PASSWORD', 'fraud_schema')}\n`,
};

for (const [svc, specific] of Object.entries(services)) {
  writeIfAbsent(path.join(root, 'services', svc, '.env'), `# Generated by scripts/setup-dev-env.mjs\n${common}${specific}`);
}

writeIfAbsent(
  path.join(root, 'services', 'api-gateway', '.env'),
  `# Generated by scripts/setup-dev-env.mjs
PORT=8000
NODE_ENV=development
LOG_LEVEL=info
REDIS_URL="redis://:${env.REDIS_PASSWORD}@localhost:6380"
CORS_ORIGINS=${env.CORS_ORIGINS}
AUTH_SERVICE_URL=http://localhost:8001
CUSTOMER_SERVICE_URL=http://localhost:8002
ACCOUNT_SERVICE_URL=http://localhost:8003
TRANSACTION_SERVICE_URL=http://localhost:8004
NOTIFICATION_SERVICE_URL=http://localhost:8005
FRAUD_SERVICE_URL=http://localhost:8006
`
);
